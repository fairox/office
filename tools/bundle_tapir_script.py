#!/usr/bin/env python3
"""Generate archicad/OfficeBuild.py, the single file for Tapir's script palette.

    python3 tools/bundle_tapir_script.py            write it
    python3 tools/bundle_tapir_script.py --check    exit 1 if it is out of date

The bundle is archicad/build_office.py (library + CLI) up to and including the line
`B = sys.modules[__name__]`, then archicad/office_gui.py, under a PEP 723 header, so
`uv run --script OfficeBuild.py --port N` opens the window with nothing to install.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = "archicad/build_office.py"
GUI = "archicad/office_gui.py"
OUT = "archicad/OfficeBuild.py"
MARKER = "B = sys.modules[__name__]"

HEADER = '''#!/usr/bin/env python3
# /// script
# requires-python = ">=3.8"
# dependencies = []
# ///
# Office Configurator: Build in Archicad. GENERATED by tools/bundle_tapir_script.py from
# archicad/build_office.py and archicad/office_gui.py; edit those, then regenerate.
'''


def bundle(lib_src, gui_src):
    lib_lines = lib_src.splitlines()
    cut = next((i for i, line in enumerate(lib_lines) if line.startswith(MARKER)), None)
    if cut is None:
        raise SystemExit(f"{LIB} has no '{MARKER}' line.")
    lib = "\n".join(line for line in lib_lines[:cut + 1] if not line.startswith("#!"))
    gui = "\n".join(line for line in gui_src.splitlines() if not line.startswith("#!"))
    return HEADER + "\n# ======== library (build_office.py) ========\n" + lib + "\n\n# ======== window (office_gui.py) ========\n" + gui + "\n"


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def main():
    text = bundle(read(LIB), read(GUI))
    path = os.path.join(ROOT, OUT)
    if "--check" in sys.argv:
        current = read(OUT) if os.path.exists(path) else ""
        if current != text:
            print(f"{OUT} is out of date: run python3 tools/bundle_tapir_script.py")
            return 1
        print(f"{OUT} is up to date.")
        return 0
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"Wrote {OUT} ({len(text.splitlines())} lines).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
